/** Pin a machine-code-qualified GTK runtime for offline browser exports. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {deflateRawSync} from 'node:zlib';
import {writeZip,readZip} from '../src/project/zip.js';
import {verifyLinuxAOTRuntime} from '../packages/linux-native/src/elf.js';
import {readLinuxAOTSourceProvenance,linuxAOTExecutionVerification,linuxAOTRuntimePayloadFile} from './linux-aot-provenance.mjs';
import {linuxTarget} from '../packages/linux-native/src/target.js';
const root=path.resolve(import.meta.dirname,'..');
export function compressedLinuxRuntimeArchive(bytes,architecture='x64') {
  const original=writeZip({['runtime-'+linuxTarget(architecture).architecture]:bytes}),view=new DataView(original.buffer);
  const central=view.getUint32(original.length-6,true),data=30+view.getUint16(26,true)+view.getUint16(28,true);
  const compressed=new Uint8Array(deflateRawSync(bytes,{level:9}));
  const result=new Uint8Array(data+compressed.length+original.length-central),output=new DataView(result.buffer),directory=data+compressed.length;
  result.set(original.subarray(0,data));result.set(compressed,data);result.set(original.subarray(central),directory);
  output.setUint16(8,8,true);output.setUint32(18,compressed.length,true);output.setUint16(10,0,true);output.setUint16(12,33,true);
  output.setUint16(directory+10,8,true);output.setUint32(directory+20,compressed.length,true);output.setUint16(directory+12,0,true);output.setUint16(directory+14,33,true);
  output.setUint32(result.length-6,directory,true);return result;
}
export async function encodeLinuxAOTRuntimePayload(runtime,{sourceRoot=root,proof}={}) {
  await verifyLinuxAOTRuntime(runtime.bytes,runtime.manifest);
  for(const [name,value]of Object.entries(readLinuxAOTSourceProvenance(sourceRoot)))
    if(runtime.manifest.provenance?.[name]!==value)throw new Error('Linux runtime was compiled from different source: '+name);
  const verification=linuxAOTExecutionVerification(proof,runtime.manifest);
  const archive=compressedLinuxRuntimeArchive(runtime.bytes,runtime.manifest.architecture),files=await readZip(archive,{maxExpandedBytes:64*1024*1024,maxFiles:1}),roundtrip=files.get('runtime-'+runtime.manifest.architecture);
  if(files.size!==1||roundtrip?.length!==runtime.bytes.length||!roundtrip.every((value,index)=>value===runtime.bytes[index]))throw new Error('Linux runtime compression round trip failed.');
  const manifest={...runtime.manifest,verification};
  return '// Generated by tools/embed-linux-aot-runtime.mjs from execution-verified SDK sources.\n// Contains an execution-qualified GTK native runtime; projects are separately compiled into machine code.\nexport const LINUX_AOT_RUNTIME_MANIFEST='+JSON.stringify(manifest)+';\nexport const LINUX_AOT_RUNTIME_ZIP_BASE64='+JSON.stringify(Buffer.from(archive).toString('base64'))+';\n';
}
export async function embedLinuxAOTRuntime(directory,reportFile,{out}={}) {
  const manifest=JSON.parse(await fs.readFile(path.join(directory,'runtime.json'),'utf8')),target=linuxTarget(manifest.architecture);
  const bytes=new Uint8Array(await fs.readFile(path.join(directory,'runtime-'+target.architecture)));
  out??=path.join(root,'packages/linux-native/src',linuxAOTRuntimePayloadFile(target.option,manifest.toolkit??'gtk3'));
  const proof=JSON.parse(await fs.readFile(reportFile,'utf8')),payload=await encodeLinuxAOTRuntimePayload({bytes,manifest},{proof});
  await fs.writeFile(out,payload);return {bytes:bytes.length,payloadBytes:Buffer.byteLength(payload),sha256:manifest.sha256};
}
