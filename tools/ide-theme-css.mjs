import {themeDetailTokens} from './theme-detail-css.mjs';
import {iconPackTokens} from './icon-pack-css.mjs';
/** IDE-only palette generation; never concatenate this into vb6-controls.css. */
import fs from 'node:fs';
import {OPTIONAL_IDE_THEMES} from '../src/theme/ide-appearance.js';
import {SYSTEM_ROLES} from '../src/theme/theme.js';
const kebab = value => value.replace(/[A-Z]/g, c => '-'+c.toLowerCase());
export function renderIdeThemePalettes() {
  let css='/* Generated by tools/ide-theme-css.mjs. IDE preference scope stays independent of application appearance. */\n';
  for (const theme of Object.values(OPTIONAL_IDE_THEMES)) {
    const root=`html[data-ide-theme="${theme.id}"]`;
    css+=`${root},\n${root} :where(.classic-menu:not(.runtime-popup), .classic-tooltip, .property-color-popup),\n.ide-theme-preview[data-preview-theme="${theme.id}"] {\n`;
    for (const [key,value] of Object.entries(theme.colors)) css+=`  --vb-${kebab(key)}: ${value};\n`;
    for (const [key,value] of Object.entries(theme.tokens)) css+=`  --ide-${kebab(key)}: ${value};\n`;
    css+=`  --vb-font: var(--ide-font); --vb-size: var(--ide-size);\n`;
    css+=`  --vb-error: var(--ide-error); --vb-button-face: var(--vb-face); --button-shadow: var(--ide-border); --ui-font: var(--ide-font);\n`;
    // Rebind system colors locally: CSS variable references otherwise resolve
    // in the inherited classic boundary before the IDE override is applied.
    SYSTEM_ROLES.forEach((role,i)=>css+=`  --vb-sys-${i}: var(--vb-${kebab(role)});\n`);
    const colors=theme.scheme==='dark'?{k:theme.colors.text,w:theme.colors.window,f:theme.colors.face,s:'#b0b0b0',d:'#cccccc',n:'#8dc8ff',b:'#8dc8ff',t:'#77d5cf',c:'#77d5cf',g:'#9ccc8a',l:'#b1e59b',o:'#f5d285',y:'#ffe58a',h:'#fff2b9',r:'#f1ada4',e:'#ffb4ab',m:'#dbadff'}:null;
    if (colors) for (const [key,value] of Object.entries(colors)) css+=`  --vb-icon-${key}: ${value};\n`;
    css+=iconPackTokens(theme);
    css+=themeDetailTokens(theme);
    css+=`  color-scheme: ${theme.scheme};\n}\n`;
  }
  return css;
}
export function writeIdeThemePalettes() {
  fs.writeFileSync(new URL('../src/theme/ide-palettes.css',import.meta.url),renderIdeThemePalettes());
}
