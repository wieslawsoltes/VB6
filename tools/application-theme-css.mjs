/** Skin tokens are reset at every boundary. The component sheet uses classic
 * fallbacks, so a classic app inside a modern IDE/app cannot inherit its skin. */
import fs from 'node:fs';
import {THEMES} from '../src/theme/theme.js';
const kebab=s=>s.replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
const keys=['radius','windowRadius','controlShadow','pressedShadow','inputShadow','hoverShadow','border','separator','surface','focus','thumb','font','captionWeight','captionBackground','windowShadow','frameImage','frameBorder','pressedPadding','disabledShadow','disabledTextShadow','progressFill','checkBackground','checkMark','checkBorder','checkShadow','radioRadius','rangeTrack','rangeThumb','material','backdrop','duration','focusWidth','focusStyle','windowButtonRadius','radioTransform','disabledColor','formIconShadow','legacyIconDisplay','treeIconBorderWidth','treeIconBackground','tabShadow'];
export function renderApplicationThemeTokens(){
  let css='/* Generated by tools/application-theme-css.mjs. No IDE selectors. */\n';
  for(const p of Object.values(THEMES)){
    css+=`[data-vb-theme="${p.id}"] {\n`;
    if(!p.family){for(const key of keys)css+=` --app-${kebab(key)}: initial;\n`;}
    else {
      const t=p.tokens,x=p.family==='x11',mac=p.family==='macos26';
      const values={radius:t.radius,windowRadius:t.windowRadius,controlShadow:x?t.controlShadow:`inset 0 0 0 1px ${t.border}, ${t.controlShadow}`,
        pressedShadow:x?t.pressedShadow:`inset 0 0 0 1px ${t.focus}, ${t.pressedShadow}`,
        inputShadow:`inset 0 0 0 1px ${t.border}`,hoverShadow:`inset 0 0 0 1px ${t.focus}`,border:t.border,separator:t.separator,
        surface:t.surface,focus:t.focus,thumb:t.thumb,font:t.font,captionWeight:'600',captionBackground:t.material,
        windowShadow:t.shadow,frameImage:'none',frameBorder:t.border,pressedPadding:'4px 9px',disabledShadow:`inset 0 0 0 1px ${p.colors.gray}`,
        disabledTextShadow:'none',progressFill:p.colors.selection,checkBackground:p.colors.selection,checkMark:p.colors.selectionText,
        checkBorder:p.colors.selection,checkShadow:'none',radioRadius:x?'0px':'50%',rangeTrack:t.separator,rangeThumb:p.colors.selection,
        material:t.material,backdrop:mac?'blur(12px) saturate(1.1)':'none',duration:'90ms',focusWidth:'2px',focusStyle:'solid',windowButtonRadius:mac?'50%':t.radius,radioTransform:x?'rotate(45deg)':'none',disabledColor:p.colors.gray,formIconShadow:'none',legacyIconDisplay:'none',treeIconBorderWidth:'0px',treeIconBackground:'transparent',tabShadow:`inset 0 -2px ${p.colors.selection}`};
      for(const key of keys)css+=` --app-${kebab(key)}: ${values[key]};\n`;
    }
    css+='}\n';
  }
  css+=`[data-vb-theme-family="macos26"][data-vb-reduce-transparency="true"] {--app-backdrop:none;--app-material:var(--vb-face);--app-caption-background:var(--vb-title);}
[data-vb-reduce-motion="true"] {--app-duration:0s;}
@media(prefers-reduced-motion:reduce) {[data-vb-theme]{--app-duration:0s;}}
@media(prefers-reduced-transparency:reduce) {[data-vb-theme-family="macos26"]{--app-backdrop:none;--app-material:var(--vb-face);--app-caption-background:var(--vb-title);}}
`;
  return css;
}
export function writeApplicationThemeTokens(){fs.writeFileSync(new URL('../src/theme/application-palettes.css',import.meta.url),renderApplicationThemeTokens());}
